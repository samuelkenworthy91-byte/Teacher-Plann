export const pushSubscriptions = pgTable(
  "push_subscriptions",
  {
    id: serial("id").primaryKey(),
    userId: integer("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    // the browser push service endpoint (unique per device/browser)
    endpoint: text("endpoint").notNull().unique(),
    p256dh: text("p256dh").notNull(),
    auth: text("auth").notNull(),
    userAgent: text("user_agent").notNull().default(""),
    createdAt: timestamp("created_at").defaultNow().notNull(),
  },
  (t) => [index("push_subs_user_idx").on(t.userId)],
);

// One row per (user, day, kind) so daily digests are never sent twice.
export const pushLog = pgTable(
  "push_log",
  {
    id: serial("id").primaryKey(),
    userId: integer("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    day: date("day", { mode: "string" }).notNull(),
    kind: text("kind").notNull(),
    sentAt: timestamp("sent_at").defaultNow().notNull(),
  },
  (t) => [uniqueIndex("push_log_user_day_kind_idx").on(t.userId, t.day, t.kind)],
);

// Tiny key/value store (holds auto-generated VAPID keys when no env vars exist)
export const appConfig = pgTable("app_config", {
  key: text("key").primaryKey(),
  value: text("value").notNull(),
});

export type User = typeof users.$inferSelect;
export type ClassRow = typeof classes.$inferSelect;
export type SlotRow = typeof timetableSlots.$inferSelect;
export type PlanRow = typeof markingPlans.$inferSelect;
export type EntryRow = typeof markingEntries.$inferSelect;
export type SettingsRow = typeof userSettings.$inferSelect;
export type PushSubscriptionRow = typeof pushSubscriptions.$inferSelect;
